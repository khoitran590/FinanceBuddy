"""Application capabilities; no storage framework imports belong here."""
from typing import Protocol, Iterable
from src.domain.models import Transaction, CategoryRule
from src.domain.banking import PlaidItem


class TransactionStore(Protocol):
    def get_category_rules(self) -> list[CategoryRule]: ...
    def apply_plaid_sync(self, item_id: str, expected_cursor: str | None, next_cursor: str,
                         upserts: Iterable[Transaction], removed_ids: Iterable[str], synced_at: str,
                         *, expected_generation: int = 0, reconcile: bool = False) -> dict: ...
    def append_statement(self, transactions, *, keep_matching=False, operation_id=None) -> dict: ...
    def undo_import_batch(self, batch_id: str) -> int: ...
    def restore_backup(self, raw_json: bytes) -> dict: ...
    def correct_category(self, transaction_id: str, category: str, keyword: str = '', apply_similar: bool = False) -> dict: ...


class BankStore(Protocol):
    def save_item(self, item_id: str, encrypted_access_token: str, institution_name: str) -> None: ...
    def save_accounts(self, item_id: str, accounts: list[dict]) -> None: ...
    def get_item(self, item_id: str) -> PlaidItem | None: ...
    def get_items(self) -> list[PlaidItem]: ...
    def get_accounts(self, item_id: str | None = None) -> list[dict]: ...
    def set_error(self, item_id: str, message: str) -> None: ...
    def begin_disconnect(self, item_id: str, remove_transactions: bool) -> bool: ...
    def finish_disconnect(self, item_id: str) -> int: ...


class TransactionReadStore(Protocol):
    def get_catalog(self) -> dict: ...
    def get_page(self, filters: dict | None = None, *, limit: int = 200, after: dict | None = None) -> dict: ...
    def get_filtered(self, filters: dict | None = None) -> list[Transaction]: ...
    def get_summary(self, filters: dict | None = None) -> dict: ...
